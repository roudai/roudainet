/** 判断の図の 1 つ */
export interface PllMark {
  /** 色を残すステッカーの番号(megaminx-image の README の Sticker order)。ほかの側面は濃い灰色 */
  show: number[]
  /**
   * 矢印の組 `[from, to]`(megaminx-image の README の Sticker order)。無くてもよい。
   * 向きは「揃えるには、from にあるピースが to へ行く」。`[a, b]` と `[b, a]` を両方書くと両矢印(2 点交換)
   */
  arrows?: [number, number][]
  /**
   * true なら、手順の先頭の括弧の AUF(`(U)` など)を回した後の向き(手順の本体を回し始める向き)で描く。無ければ、横のケースの図と同じ向き。
   * show と arrows の番号は、描く向きで数える。先頭に AUF が無い手順では、付けても変わらない
   */
  start?: true
  /** 図の下に添える説明('バー'、'偽ペア' など)。無くてもよい。長いときは \n で改行の位置を書く(書いた位置でだけ改行する) */
  label?: string
}

